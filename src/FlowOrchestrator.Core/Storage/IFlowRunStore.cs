using FlowOrchestrator.Core.Abstractions;

namespace FlowOrchestrator.Core.Storage;

/// <summary>
/// Persistence contract for flow run lifecycle: creating runs, recording step progress,
/// completing runs, and querying run history.
/// </summary>
public interface IFlowRunStore
{
    /// <summary>
    /// Creates a new run record in <c>Running</c> status and returns it.
    /// Called once per <c>TriggerAsync</c> invocation.
    /// </summary>
    /// <param name="flowId">The flow definition this run belongs to.</param>
    /// <param name="flowName">Display name of the flow at trigger time.</param>
    /// <param name="runId">Unique identifier for this run, generated by the engine.</param>
    /// <param name="triggerKey">The manifest trigger key that fired (e.g. <c>"manual"</c>, <c>"schedule"</c>).</param>
    /// <param name="triggerData">JSON-serialised trigger payload, or <see langword="null"/>.</param>
    /// <param name="jobId">Runtime job ID (e.g. Hangfire BackgroundJobId) for cross-referencing, or <see langword="null"/>.</param>
    /// <param name="sourceRunId">When this run was created via "Re-run all" on a previous run, the ID of that run; otherwise <see langword="null"/>.</param>
    Task<FlowRunRecord> StartRunAsync(Guid flowId, string flowName, Guid runId, string triggerKey, string? triggerData, string? jobId, Guid? sourceRunId = null);

    /// <summary>
    /// Returns runs whose <see cref="FlowRunRecord.SourceRunId"/> equals <paramref name="sourceRunId"/>,
    /// i.e. all re-runs derived from a given run. Used by the dashboard to render lineage.
    /// </summary>
    Task<IReadOnlyList<FlowRunRecord>> GetDerivedRunsAsync(Guid sourceRunId)
        => Task.FromResult<IReadOnlyList<FlowRunRecord>>(Array.Empty<FlowRunRecord>());

    /// <summary>
    /// Records the start of a step attempt: sets status to <c>Running</c>, persists inputs, and associates the Hangfire job ID.
    /// </summary>
    Task RecordStepStartAsync(Guid runId, string stepKey, string stepType, string? inputJson, string? jobId);

    /// <summary>
    /// Records the start of a step attempt like <see cref="RecordStepStartAsync(Guid, string, string, string?, string?)"/>,
    /// and stamps the new attempt row with the server that runs it (<see cref="FlowStepAttemptRecord.ServerId"/>).
    /// </summary>
    /// <param name="runId">The run owning the step.</param>
    /// <param name="stepKey">The step (manifest key or runtime loop path).</param>
    /// <param name="stepType">The step's handler type name.</param>
    /// <param name="inputJson">JSON-serialised unresolved inputs, or <see langword="null"/>.</param>
    /// <param name="jobId">Runtime job id, or <see langword="null"/>.</param>
    /// <param name="serverId">The process's server id (<see cref="FlowServerRecord.ServerId"/>), or <see langword="null"/> when unknown.</param>
    /// <returns>A task that completes when the start is durable.</returns>
    /// <remarks>
    /// The engine calls this overload. The default implementation drops <paramref name="serverId"/> and calls the
    /// five-parameter overload, so a custom store written before 2.0 keeps working and simply records no server.
    /// The built-in stores write it into the same attempt insert — no extra round trip.
    /// </remarks>
    Task RecordStepStartAsync(Guid runId, string stepKey, string stepType, string? inputJson, string? jobId, string? serverId)
        => RecordStepStartAsync(runId, stepKey, stepType, inputJson, jobId);

    /// <summary>
    /// Records the outcome of a step attempt: updates status, persists output JSON, and sets error message on failure.
    /// </summary>
    Task RecordStepCompleteAsync(Guid runId, string stepKey, string status, string? outputJson, string? errorMessage);

    /// <summary>
    /// Records the outcome of a step exactly like <see cref="RecordStepCompleteAsync"/>, but only when the
    /// step is still <see cref="StepStatus.Running"/>, and reports whether this call made the transition.
    /// </summary>
    /// <param name="runId">The run owning the step.</param>
    /// <param name="stepKey">The runtime step key, e.g. <c>"outer.1.inner"</c>.</param>
    /// <param name="status">The terminal status to set.</param>
    /// <param name="outputJson">The step output, or <see langword="null"/>.</param>
    /// <param name="errorMessage">The failure or skip reason, or <see langword="null"/>.</param>
    /// <returns>
    /// <see langword="true"/> when this call moved a <c>Running</c> step to <paramref name="status"/>;
    /// <see langword="false"/> when the step was no longer <c>Running</c> (another writer won, or it has no row).
    /// </returns>
    /// <remarks>
    /// The engine settles a <c>ForEach</c> loop step through this method. A loop step is the only step whose
    /// completion is decided outside its own handler, by whichever worker completes the loop's last
    /// outstanding child, so two workers can decide it at the same moment. Only the caller that wins the
    /// transition publishes the loop's <c>StepCompletedEvent</c> and continues the graph from it. The check
    /// and the write must be one atomic step (a conditional <c>UPDATE</c> and its row count, or a lock).
    /// There is deliberately no default implementation: an unconditional fallback would bring the double
    /// settle back without any compile-time signal.
    /// </remarks>
    Task<bool> TryCompleteRunningStepAsync(Guid runId, string stepKey, string status, string? outputJson, string? errorMessage);

    /// <summary>
    /// Marks the run as complete (status: <c>Succeeded</c>, <c>Failed</c>, or <c>Cancelled</c>)
    /// and sets <see cref="FlowRunRecord.CompletedAt"/>.
    /// </summary>
    Task CompleteRunAsync(Guid runId, string status);

    /// <summary>
    /// Transitions the run to a terminal <paramref name="status"/> only if it is still active
    /// (<c>Running</c>), reporting whether this call performed the transition. Makes run completion
    /// idempotent and safe against concurrent completers — notably the graph continuation and the
    /// periodic timeout sweep (single- or multi-instance) — so a run's lifecycle event is published
    /// exactly once and its terminal status is set by exactly one writer.
    /// </summary>
    /// <param name="runId">The run to complete.</param>
    /// <param name="status">The terminal status to set.</param>
    /// <returns>
    /// <see langword="true"/> if this call transitioned a <c>Running</c> run to <paramref name="status"/>;
    /// <see langword="false"/> if the run was already in a terminal state (another writer won).
    /// </returns>
    /// <remarks>
    /// Default implementation delegates to <see cref="CompleteRunAsync"/> and reports <see langword="true"/>,
    /// so existing custom <see cref="IFlowRunStore"/> implementations compile unchanged (retaining their
    /// prior, non-idempotent completion behaviour).
    /// </remarks>
    async Task<bool> CompleteRunIfActiveAsync(Guid runId, string status)
    {
        await CompleteRunAsync(runId, status).ConfigureAwait(false);
        return true;
    }

    /// <summary>
    /// Returns a page of run records, optionally filtered by <paramref name="flowId"/>.
    /// Results are ordered by start time descending.
    /// </summary>
    Task<IReadOnlyList<FlowRunRecord>> GetRunsAsync(Guid? flowId = null, int skip = 0, int take = 50);

    /// <summary>
    /// Returns a paginated run list with total count, optionally filtered by flow, status,
    /// and free-text search.
    /// </summary>
    /// <param name="flowId">Restricts results to a single flow when set.</param>
    /// <param name="status">Restricts results to runs in the given status when set.</param>
    /// <param name="skip">Number of leading rows to skip (offset pagination).</param>
    /// <param name="take">Maximum number of rows to return.</param>
    /// <param name="search">
    /// Free-text term matched (case-insensitively) against run identity columns and the
    /// current step records (step key, error message, output JSON). Step <i>attempt</i>
    /// history is intentionally not searched — its output duplicates the current step row.
    /// </param>
    Task<(IReadOnlyList<FlowRunRecord> Runs, int TotalCount)> GetRunsPageAsync(Guid? flowId = null, string? status = null, int skip = 0, int take = 50, string? search = null);

    /// <summary>
    /// Tiered, time-bounded variant of <see cref="GetRunsPageAsync(Guid?, string?, int, int, string?)"/>.
    /// </summary>
    /// <remarks>
    /// <c>deepSearch: true</c> (the behaviour of the five-argument overload) also matches the current
    /// step records; <c>deepSearch: false</c> matches only the top-level run columns (id, flow name,
    /// trigger key, status, background job id) — index-friendlier, suited to typeahead such as the
    /// command palette. <c>startedFrom</c> / <c>startedTo</c> bound the scan to a start-time window
    /// when set.
    /// The default implementation delegates to the five-argument overload, so existing
    /// <see cref="IFlowRunStore"/> providers keep compiling and stay correct (they simply do not get
    /// the quick-search or time-window optimisations until they override this method).
    /// </remarks>
    Task<(IReadOnlyList<FlowRunRecord> Runs, int TotalCount)> GetRunsPageAsync(Guid? flowId, string? status, int skip, int take, string? search, bool deepSearch, DateTimeOffset? startedFrom = null, DateTimeOffset? startedTo = null)
        => GetRunsPageAsync(flowId, status, skip, take, search);

    /// <summary>
    /// Returns one page of runs matching a structured <paramref name="query"/>, newest first, without
    /// counting the whole filtered set unless <see cref="RunSearchQuery.CountsTotal"/> allows it.
    /// </summary>
    /// <param name="query">The filters, window and page to read.</param>
    /// <param name="cancellationToken">Cancels the read.</param>
    /// <returns>The page, whether more rows follow it, and an exact total when one was requested and cheap.</returns>
    /// <remarks>
    /// This is the run-list path the dashboard uses. The built-in providers override it so that a run
    /// id is a primary-key seek, a text term reads only the run's own columns inside the start-time
    /// window, and step payloads are read only when <see cref="RunSearchQuery.IncludeStepPayloads"/> is
    /// set. The default implementation keeps third-party providers correct by delegating to
    /// <see cref="GetRunsPageAsync(Guid?, string?, int, int, string?, bool, DateTimeOffset?, DateTimeOffset?)"/>;
    /// it does not get the seeks. That overload orders runs newest first but leaves runs that share a start
    /// time in no defined order, so the default implementation re-sorts every page into the cursor order
    /// (<c>StartedAt</c> descending, then <c>Id</c> ascending) and pages exactly — no run duplicated or
    /// dropped — whatever the number of ties:
    /// <list type="bullet">
    /// <item>with <see cref="RunSearchQuery.After"/>, it reads the runs that started at the cursor's exact
    /// start time as one group (a <c>startedFrom = startedTo</c> window), keeps those after the cursor, and
    /// reads the rest strictly older than the cursor;</item>
    /// <item>when the page's last row shares its start time with rows the read did not reach, it reads
    /// that whole tie group too, so <see cref="RunSearchPage.NextCursor"/> never skips a tied run.</item>
    /// </list>
    /// A tie group is read with growing page sizes until the overload returns fewer rows than asked, so
    /// the extra reads are proportional to the number of tied runs and happen only on a tie. Exactness
    /// relies on the overload honouring <c>startedFrom</c> / <c>startedTo</c>; with a
    /// <see cref="RunSearchQuery.Skip"/>, offset semantics apply to the rows older than the cursor, as they
    /// do on the built-in providers. <see cref="RunSearchQuery.TotalCountCap"/> is applied to the exact
    /// count the legacy overload returns.
    /// </remarks>
    async Task<RunSearchPage> SearchRunsAsync(RunSearchQuery query, CancellationToken cancellationToken = default)
    {
        ArgumentNullException.ThrowIfNull(query);
        cancellationToken.ThrowIfCancellationRequested();

        // A run id falls back to a substring match on the legacy overload, then is narrowed to the
        // exact id here. Text, when also present, wins the store-side match.
        var search = query.HasText ? query.Text : query.RunId?.ToString("D");
        var take = Math.Clamp(query.Take, 0, int.MaxValue - 1);
        var skip = Math.Max(0, query.Skip);
        var rows = new List<FlowRunRecord>(Math.Min(take + 1, 256));
        var upper = query.StartedTo;
        int? total = null;

        if (query.After is { } after)
        {
            var cursorInWindow = (query.StartedTo is null || after.StartedAt <= query.StartedTo)
                && (query.StartedFrom is null || after.StartedAt >= query.StartedFrom);
            if (cursorInWindow)
            {
                var group = await ReadTieGroupAsync(query, search, after.StartedAt).ConfigureAwait(false);
                // Serves the dashboard's polled run search (CLAUDE.md hot path): foreach + continue, no closure.
                foreach (var run in group)
                {
                    if (!after.Precedes(run) || (query.RunId is { } id && run.Id != id))
                        continue;
                    if (skip > 0)
                    {
                        skip--;
                        continue;
                    }

                    rows.Add(run);
                }
            }

            // Strictly older than the cursor: the legacy window is inclusive, and the cursor's own start
            // time was read above as a whole group.
            var older = after.StartedAt.AddTicks(-1);
            upper = upper is { } to && to < older ? to : older;
        }

        var groupRows = rows.Count;
        var need = take + 1 - groupRows;
        if (need > 0 && (query.StartedFrom is null || upper is null || upper >= query.StartedFrom))
        {
            var (batch, batchTotal) = await GetRunsPageAsync(
                query.FlowId, query.Status, skip, need, search,
                query.IncludeStepPayloads, query.StartedFrom, upper).ConfigureAwait(false);
            total = batchTotal;

            DateTimeOffset? boundary = null;
            // foreach, not .Where(): the captured filters would allocate a closure on every search call
            // through this default implementation; CLAUDE.md prefers the loop.
            foreach (var run in batch)
            {
                if (boundary is null || run.StartedAt < boundary)
                    boundary = run.StartedAt;
                if (query.RunId is { } id && run.Id != id)
                    continue;
                rows.Add(run);
            }

            rows.Sort(groupRows, rows.Count - groupRows, RunSearchCursor.ListOrder);

            // The read stopped at `need` rows, so more runs may share the start time of its oldest row. If
            // that tie group reaches onto the page, NextCursor would point into the middle of a group whose
            // other members were never read: replace the partial group with the whole one. With an offset
            // (skip > 0) the group's members before the offset cannot be told apart, so offset paging keeps
            // its usual semantics.
            var lastOnPage = take - 1;
            if (batch.Count >= need && boundary is { } tie && skip == 0 && query.RunId is null
                && lastOnPage >= groupRows && lastOnPage < rows.Count && rows[lastOnPage].StartedAt == tie)
            {
                var kept = groupRows;
                for (var i = groupRows; i < rows.Count; i++)
                {
                    if (rows[i].StartedAt != tie)
                        rows[kept++] = rows[i];
                }

                rows.RemoveRange(kept, rows.Count - kept);
                rows.AddRange(await ReadTieGroupAsync(query, search, tie).ConfigureAwait(false));
            }
        }

        if (query.CountsTotal && (query.After is not null || total is null))
        {
            // With a cursor the reads above covered only the rows after it; the total is over the plain
            // filters, so take it with an empty page.
            (_, var counted) = await GetRunsPageAsync(
                query.FlowId, query.Status, 0, 0, null, false, query.StartedFrom, query.StartedTo).ConfigureAwait(false);
            total = counted;
        }

        return RunSearchPage.FromRows(rows, take, query.CountsTotal ? total ?? 0 : null, query.EffectiveTotalCountCap);
    }

    /// <summary>
    /// Reads every run matching <paramref name="query"/>'s filters that started exactly at
    /// <paramref name="startedAt"/>, in cursor order. Used by the default <see cref="SearchRunsAsync"/>.
    /// </summary>
    /// <remarks>
    /// Page sizes grow 64, 256, 1024, … until the overload returns fewer rows than asked, so the cost is
    /// proportional to the tie group and needs no count. Rows outside the instant are dropped in case the
    /// provider does not honour the window.
    /// </remarks>
    private async Task<List<FlowRunRecord>> ReadTieGroupAsync(RunSearchQuery query, string? search, DateTimeOffset startedAt)
    {
        var size = 64;
        while (true)
        {
            var (batch, _) = await GetRunsPageAsync(
                query.FlowId, query.Status, 0, size, search,
                query.IncludeStepPayloads, startedAt, startedAt).ConfigureAwait(false);
            if (batch.Count < size || size > int.MaxValue / 4)
            {
                var group = new List<FlowRunRecord>(batch.Count);
                // Polled run-search path (CLAUDE.md hot path): foreach, not .Where with a closure over query.
                foreach (var run in batch)
                {
                    if (run.StartedAt == startedAt && (query.RunId is not { } id || run.Id == id))
                        group.Add(run);
                }

                group.Sort(RunSearchCursor.ListOrder);
                return group;
            }

            size *= 4;
        }
    }

    /// <summary>
    /// Returns full run detail including all step records and their attempt history,
    /// or <see langword="null"/> if no run with <paramref name="runId"/> exists.
    /// </summary>
    Task<FlowRunRecord?> GetRunDetailAsync(Guid runId);

    /// <summary>
    /// Returns the run's header row only — no step records, no attempt history — or
    /// <see langword="null"/> if no run with <paramref name="runId"/> exists.
    /// </summary>
    /// <param name="runId">The run to read.</param>
    /// <remarks>
    /// For callers that need a field or two off the run itself (its <c>FlowId</c>, its status) and
    /// have no use for the step graph. <see cref="GetRunDetailAsync"/> issues three queries and
    /// returns every step row and every attempt row <i>including</i> their unbounded JSON columns,
    /// so its cost grows with the size of the run; on SQL Server that read has been observed to time
    /// out on a 150-iteration <c>ForEach</c> under load. Use this instead wherever the graph is not
    /// actually read.
    /// <para>
    /// The default implementation delegates to <see cref="GetRunDetailAsync"/> so existing custom
    /// stores keep compiling and keep working — they simply do not get the saving. Providers should
    /// override it with a single-row query.
    /// </para>
    /// </remarks>
    Task<FlowRunRecord?> GetRunAsync(Guid runId) => GetRunDetailAsync(runId);

    /// <summary>
    /// Returns a single step's row — status, error, timestamps and its own JSON columns — or
    /// <see langword="null"/> when the run or the step has no row yet.
    /// </summary>
    /// <param name="runId">The run owning the step.</param>
    /// <param name="stepKey">The runtime step key (e.g. <c>"process.3.validate"</c>).</param>
    /// <remarks>
    /// <see cref="FlowStepRecord.Attempts"/> is not populated. Exists for
    /// <c>@steps('key').status</c> / <c>.error</c> expressions, which are resolved per step execution
    /// and per <c>when</c>-clause evaluation: fetching the whole run detail for them pulled every step
    /// and attempt row with their JSON columns on each of those calls (#189).
    /// <para>
    /// The default implementation delegates to <see cref="GetRunDetailAsync"/> and scans, so existing
    /// custom stores keep working without the saving. Providers should override it with a point read.
    /// </para>
    /// </remarks>
    async Task<FlowStepRecord?> GetStepAsync(Guid runId, string stepKey)
    {
        var run = await GetRunDetailAsync(runId).ConfigureAwait(false);
        if (run?.Steps is not { } steps)
        {
            return null;
        }

        foreach (var step in steps)
        {
            if (string.Equals(step.StepKey, stepKey, StringComparison.Ordinal))
            {
                return step;
            }
        }

        return null;
    }

    /// <summary>Returns aggregate counts used by the dashboard overview panel.</summary>
    Task<DashboardStatistics> GetStatisticsAsync();

    /// <summary>
    /// Returns time-bucketed run counts and duration percentiles for the half-open
    /// interval [<paramref name="since"/>, <paramref name="until"/>). Buckets that contain
    /// no runs are still returned (with zero counts) so the caller can render a contiguous
    /// timeline without gap-filling. When <paramref name="flowId"/> is supplied, only runs
    /// for that flow are included.
    /// </summary>
    /// <param name="granularity">Hour or Day bucket size.</param>
    /// <param name="since">UTC start of the window (inclusive). Aligned to the granularity boundary.</param>
    /// <param name="until">UTC end of the window (exclusive). Aligned to the granularity boundary.</param>
    /// <param name="flowId">Optional filter — when non-null, only runs for this flow are counted.</param>
    Task<IReadOnlyList<RunTimeseriesBucket>> GetRunTimeseriesAsync(
        RunTimeseriesGranularity granularity,
        DateTimeOffset since,
        DateTimeOffset until,
        Guid? flowId = null)
        => Task.FromResult<IReadOnlyList<RunTimeseriesBucket>>(Array.Empty<RunTimeseriesBucket>());

    /// <summary>Returns all runs currently in <c>Running</c> status (used for timeout enforcement).</summary>
    Task<IReadOnlyList<FlowRunRecord>> GetActiveRunsAsync();

    /// <summary>
    /// Resets a <c>Failed</c> step back to a re-runnable state for a manual retry, only if it is still
    /// <c>Failed</c>, and reports whether this call made the reset.
    /// </summary>
    /// <param name="runId">The run containing the step.</param>
    /// <param name="stepKey">The step to reset.</param>
    /// <returns>
    /// <see langword="true"/> when this call reset a <c>Failed</c> step; <see langword="false"/> when the step
    /// has no row or is not <c>Failed</c> (for example because a concurrent retry reset it first). Nothing is
    /// changed when it returns <see langword="false"/>.
    /// </returns>
    /// <remarks>
    /// <para>
    /// On success, one transaction: the step row becomes <c>Running</c> with its output, error and
    /// completion time cleared; the run goes back to <c>Running</c> with no completion time; and the step's
    /// claim and dispatch-ledger rows are deleted so the engine can dispatch and claim the new attempt.
    /// </para>
    /// <para>
    /// The <c>Failed</c> check and the reset must be one atomic step (a conditional <c>UPDATE</c> and its row
    /// count, inside the same transaction as the deletes). Before 2.0 the reset was unconditional and
    /// unbatched, so a second concurrent retry deleted the first retry's claim and the handler ran twice at
    /// once (RFC 2.0 S4). There is deliberately no default implementation.
    /// </para>
    /// </remarks>
    Task<bool> RetryStepAsync(Guid runId, string stepKey);

    /// <summary>
    /// Clears cascade-skip records (<see cref="StepSkipReasons.PrerequisitesUnmet"/>) for the
    /// given step keys so the DAG planner re-evaluates them after a manual retry of an
    /// upstream step. Removes the step row, claim row, and dispatch-ledger row for any
    /// matching descendant — the attempt history (<c>FlowStepAttempts</c>) is preserved so
    /// the dashboard still surfaces the prior "Skipped" attempt as audit trail.
    /// </summary>
    /// <remarks>
    /// Only rows whose status is <c>Skipped</c> AND whose error message exactly matches
    /// <see cref="StepSkipReasons.PrerequisitesUnmet"/> are cleared. Steps skipped via
    /// <c>When</c>-clause evaluation carry a different reason and are intentionally left
    /// untouched. Idempotent — calling with keys that have no matching row is a no-op.
    /// Default implementation is a no-op so external <see cref="IFlowRunStore"/>
    /// implementations continue to compile; in that case the post-retry DAG advance
    /// behaves as pre-fix (downstream steps stay <c>Skipped</c>).
    /// </remarks>
    Task ResetCascadeSkippedDependentsAsync(Guid runId, IReadOnlyCollection<string> stepKeys)
        => Task.CompletedTask;

    /// <summary>
    /// Atomically records that a step has been dispatched for execution.
    /// Returns <see langword="true"/> if this is the first dispatch for this step in this run;
    /// <see langword="false"/> if the step was already dispatched (idempotent guard — caller should skip).
    /// </summary>
    /// <remarks>
    /// Must use an atomic INSERT-if-not-exists primitive (SQL <c>WHERE NOT EXISTS</c>,
    /// PostgreSQL <c>ON CONFLICT DO NOTHING</c>, or <see cref="System.Collections.Concurrent.ConcurrentDictionary{TKey,TValue}.TryAdd"/>).
    /// </remarks>
    Task<bool> TryRecordDispatchAsync(Guid runId, string stepKey, CancellationToken ct = default);

    /// <summary>
    /// Stores the runtime job or message ID returned by the dispatcher alongside the dispatch record.
    /// Best-effort — implementations should not throw; failures are silently ignored by the engine.
    /// </summary>
    Task AnnotateDispatchAsync(Guid runId, string stepKey, string jobId, CancellationToken ct = default);

    /// <summary>
    /// Removes the dispatch record for a step, allowing it to be re-dispatched.
    /// Called by the engine before rescheduling a <see cref="StepStatus.Pending"/> (polling) step.
    /// </summary>
    Task ReleaseDispatchAsync(Guid runId, string stepKey, CancellationToken ct = default);

    /// <summary>
    /// Returns the set of step keys that have been dispatched (and not yet released) for a run.
    /// Used by the recovery service to avoid re-dispatching already-in-flight steps.
    /// </summary>
    Task<IReadOnlySet<string>> GetDispatchedStepKeysAsync(Guid runId);

    /// <summary>
    /// Returns whether one specific step currently holds a dispatch-ledger row for the run.
    /// </summary>
    /// <param name="runId">The run owning the step.</param>
    /// <param name="stepKey">The runtime step key to test, e.g. <c>"loop.3.child"</c>.</param>
    /// <returns><see langword="true"/> when a live (not released) dispatch record exists for <c>(runId, stepKey)</c>.</returns>
    /// <remarks>
    /// A point lookup for callers that need membership rather than enumeration — notably the engine's
    /// <c>ForEach</c> admission gate, which runs on every step completion while a loop is parked and
    /// only ever probes the few keys around its started-iteration boundary. The ledger keeps one row
    /// per dispatched step, so <see cref="GetDispatchedStepKeysAsync"/> grows with run length and
    /// answering a single-key question through it is O(n) in both payload and scan. The default
    /// implementation does exactly that, so existing stores keep compiling — override it with an
    /// indexed lookup.
    /// </remarks>
    async Task<bool> IsStepDispatchedAsync(Guid runId, string stepKey)
    {
        var dispatched = await GetDispatchedStepKeysAsync(runId).ConfigureAwait(false);
        return dispatched.Contains(stepKey);
    }

    /// <summary>
    /// Finds dispatch-ledger rows whose hand-off to the runtime never completed, and leases them to the
    /// caller for re-delivery.
    /// </summary>
    /// <param name="minimumAge">How long a row must have gone without a runtime job id to qualify.</param>
    /// <param name="maxCount">Upper bound on the rows returned by one call.</param>
    /// <param name="ct">Honoured before the lease is written; never after.</param>
    /// <returns>
    /// The leased rows; empty when nothing qualifies or the store does not support the lease.
    /// </returns>
    /// <remarks>
    /// <para>
    /// The engine writes a ledger row <em>before</em> it hands the step to the runtime and annotates it
    /// with the runtime's job/message id (<see cref="AnnotateDispatchAsync"/>) once the hand-off returns.
    /// A row that still has no id long after it was written means the hand-off never returned: the process
    /// died mid-send, or the send is hung. Startup recovery skips every ledgered key, so without this lease
    /// such a step is never dispatched again and its run stays <c>Running</c> for ever.
    /// </para>
    /// <para>
    /// A row qualifies when all of these hold: it has no job id; it is older than
    /// <paramref name="minimumAge"/>; its run is <c>Running</c>; no worker claims the step; and the step has
    /// no status row, or only a <see cref="StepStatus.Pending"/> one (a poll whose re-attempt was never
    /// handed over). Leasing re-stamps the row's dispatch time to now, in the same atomic statement that
    /// selects it, so concurrent callers (one per replica) never lease the same row twice inside one
    /// <paramref name="minimumAge"/> window, and a re-delivery that fails again is retried a window later.
    /// </para>
    /// <para>
    /// The store cannot tell "never sent" from "sent, but the process died before the annotation". Both are
    /// re-delivered; a duplicate message is absorbed by the execution claim
    /// (<see cref="IFlowRunRuntimeStore.TryClaimStepAsync"/>), whereas a lost one strands the run.
    /// </para>
    /// <para>
    /// No default implementation, deliberately: a store that silently returned nothing would keep the stranded-run
    /// bug this member exists to close. Custom stores must implement it (see the migration guide).
    /// </para>
    /// </remarks>
    Task<IReadOnlyList<UnsentDispatch>> LeaseUnsentDispatchesAsync(TimeSpan minimumAge, int maxCount, CancellationToken ct = default);
}
