namespace FlowOrchestrator.Core.Storage;

/// <summary>
/// Persistence contract for webhook replay-attack protection. Maintains a set
/// of <c>(flowId, triggerKey, nonce)</c> tuples with expiry; a successful
/// registration means the nonce has not been seen before, a conflict means a
/// replay attack is in progress.
/// </summary>
/// <remarks>
/// Storage-neutral by design — in-memory, Sql Server, and PostgreSQL impls
/// ship in their respective projects. Pick the backend that matches your
/// deployment topology: in-memory for single-replica, Sql/Postgres for
/// multi-replica coordination.
/// </remarks>
public interface IWebhookReplayStore
{
    /// <summary>
    /// Atomically records the nonce under a fresh, unrevealed registration id. Returns <see langword="true"/>
    /// when the nonce had not been seen for this flow + trigger; <see langword="false"/> when the same tuple
    /// is already present (replay).
    /// </summary>
    /// <param name="flowId">Flow identifier scoping the dedup window.</param>
    /// <param name="triggerKey">Trigger key scoping the dedup window.</param>
    /// <param name="nonce">Unique-per-event token (timestamp + delivery-id, etc.).</param>
    /// <param name="expiresAt">When the entry may be purged.</param>
    /// <param name="ct">Cancellation propagated from the host pipeline.</param>
    /// <remarks>
    /// Delegates to the overload that takes a registration id, with a new <see cref="Guid"/> nobody keeps, so an
    /// entry recorded this way can never be released by <see cref="TryForgetAsync"/>.
    /// </remarks>
    ValueTask<bool> TryRegisterAsync(
        Guid flowId,
        string triggerKey,
        string nonce,
        DateTimeOffset expiresAt,
        CancellationToken ct = default)
        => TryRegisterAsync(flowId, triggerKey, nonce, expiresAt, Guid.NewGuid(), ct);

    /// <summary>
    /// Atomically records the nonce and remembers <paramref name="registrationId"/> as the owner of the entry.
    /// Returns <see langword="true"/> when the nonce had not been seen for this flow + trigger;
    /// <see langword="false"/> when the same tuple is already present (replay) — the existing entry, and its
    /// owner, are left untouched.
    /// </summary>
    /// <param name="flowId">Flow identifier scoping the dedup window.</param>
    /// <param name="triggerKey">Trigger key scoping the dedup window.</param>
    /// <param name="nonce">Unique-per-event token (timestamp + delivery-id, etc.).</param>
    /// <param name="expiresAt">When the entry may be purged.</param>
    /// <param name="registrationId">
    /// Secret per-request owner token. Only a caller holding it can release the entry again
    /// (<see cref="TryForgetAsync"/>). Generated by the caller with <see cref="Guid.NewGuid"/>; never derived from
    /// request data.
    /// </param>
    /// <param name="ct">Cancellation propagated from the host pipeline.</param>
    /// <remarks>
    /// Implementations bound <paramref name="nonce"/> with <see cref="WebhookReplayNonceStorage.ToStorageForm"/>,
    /// exactly as the five-argument overload does.
    /// </remarks>
    ValueTask<bool> TryRegisterAsync(
        Guid flowId,
        string triggerKey,
        string nonce,
        DateTimeOffset expiresAt,
        Guid registrationId,
        CancellationToken ct = default);

    /// <summary>
    /// Removes the entry for <c>(flowId, triggerKey, nonce)</c> only if it is still owned by
    /// <paramref name="registrationId"/> — the compensation for a delivery that passed replay protection and then
    /// failed before its run was started, so the publisher's retry is not answered as a replay.
    /// </summary>
    /// <param name="flowId">Flow identifier the entry was registered under.</param>
    /// <param name="triggerKey">Trigger key the entry was registered under.</param>
    /// <param name="nonce">The nonce exactly as passed to <see cref="TryRegisterAsync(Guid, string, string, DateTimeOffset, Guid, CancellationToken)"/>.</param>
    /// <param name="registrationId">The owner token the entry was registered with.</param>
    /// <param name="ct">Cancellation token; callers on a failure path pass <see cref="CancellationToken.None"/>.</param>
    /// <returns>
    /// <see langword="true"/> when this call removed the entry; <see langword="false"/> when no entry exists or it
    /// is owned by another registration (including any entry recorded without a known owner).
    /// </returns>
    /// <remarks>
    /// The owner match is what keeps this from opening a replay window: a replayer's own registration fails
    /// (the entry already exists), so it never holds the token of the entry that blocks it. There is
    /// deliberately no default implementation — a silent no-op would bring back the lost-retry bug this
    /// member exists to fix.
    /// </remarks>
    ValueTask<bool> TryForgetAsync(
        Guid flowId,
        string triggerKey,
        string nonce,
        Guid registrationId,
        CancellationToken ct = default);

    /// <summary>Drops every entry whose <c>ExpiresAt</c> is at or before <paramref name="now"/>.</summary>
    /// <param name="now">Reference instant; entries with <c>ExpiresAt &lt;= now</c> are removed.</param>
    /// <param name="ct">Cancellation token.</param>
    ValueTask<int> PurgeExpiredAsync(DateTimeOffset now, CancellationToken ct = default);
}
